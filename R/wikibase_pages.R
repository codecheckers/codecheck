#' Write the hosting-policy pages onto the instance
#'
#' `Project:About` and `Project:Copyrights` are what the wikibase.cloud hosting
#' policy asks every hosted instance for, and a rebuilt instance has to be
#' compliant without a manual step, so they are written like the generated index
#' pages rather than curated by hand. `Project:Copyright`, MediaWiki's own
#' footer target, is left as a redirect to the plural.
#'
#' @param session a session from [wikibase_session()]
#' @return the page titles, invisibly
#' @keywords internal
write_wikibase_policy_pages <- function(session) {
  pages <- list(
    list(title = WIKIBASE_INSTANCE$about_page,
         text = paste(wikibase_about_wikitext(), collapse = "\n")),
    list(title = WIKIBASE_INSTANCE$copyright_page,
         text = paste(wikibase_copyright_wikitext(), collapse = "\n")),
    list(title = WIKIBASE_INSTANCE$copyright_redirect,
         text = paste0("#REDIRECT [[", WIKIBASE_INSTANCE$copyright_page, "]]"))
  )

  for (page in pages) {
    wikibase_post(session, list(
      action = "edit",
      title = page$title,
      text = page$text,
      summary = "generated by codecheck::bootstrap_wikibase()",
      bot = 1
    ), what = paste0("page '", page$title, "'"))
  }

  invisible(vapply(pages, function(page) page$title, character(1)))
}
